"""Test the semantic cache's hit rate on genuine AI-paraphrased prompts
(scripts/generate_paraphrases.py), not just near-identical duplicate text.

scripts/evaluate_semantic_cache.py's duplicate-ground-truth check only
measures hit rate on near-identical normalized duplicates. This stores the
100 sampled original prompts in the cache and looks up their Gemini-
paraphrased versions instead, at the same threshold sweep, to see how the
cache actually performs on reworded (not just repeated) questions.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
from sentence_transformers import SentenceTransformer

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.semantic_cache import MODEL_NAME, SemanticCache

PARAPHRASES_PATH = ROOT / 'data/processed/semantic_cache/paraphrases.json'
RESPONSES_PATH = ROOT / 'data/processed/semantic_cache/test_with_responses.csv'
OUTPUT_PATH = ROOT / 'data/processed/semantic_cache/paraphrase_evaluation.json'
THRESHOLDS = [0.70, 0.75, 0.80, 0.85, 0.90, 0.95]


def load_records(paraphrases_path=PARAPHRASES_PATH, responses_path=RESPONSES_PATH):
    data = json.loads(paraphrases_path.read_text())
    responses = pd.read_csv(responses_path, encoding='utf-8-sig')['model_output']
    records = [dict(record) for record in data['records']]
    for record in records:
        record['response'] = responses.iloc[record['test_row']]
    return data, records


def evaluate_at_threshold(records, model, threshold):
    cache = SemanticCache(threshold=threshold, model=model)
    for record in records:
        cache.store(record['original'], record['response'])

    hits = correct = 0
    for record in records:
        result = cache.lookup(record['paraphrase'])
        if result.hit:
            hits += 1
            if result.matched_prompt == record['original']:
                correct += 1

    total = len(records)
    return {
        'threshold': threshold,
        'total': total,
        'hits': hits,
        'hit_rate': hits / total if total else None,
        'correct_matches': correct,
        'correct_match_rate_of_hits': correct / hits if hits else None,
    }


def evaluate(paraphrases_path=PARAPHRASES_PATH, responses_path=RESPONSES_PATH,
             output_path=OUTPUT_PATH):
    data, records = load_records(paraphrases_path, responses_path)
    model = SentenceTransformer(MODEL_NAME)

    results = {t: evaluate_at_threshold(records, model, t) for t in THRESHOLDS}

    report = {
        'paraphrase_model': data['model_name'],
        'embedding_model': MODEL_NAME,
        'sample_size': len(records),
        'results_by_threshold': {str(t): r for t, r in results.items()},
        'example_pairs': [
            {'original': r['original'], 'paraphrase': r['paraphrase']}
            for r in records[:5]
        ],
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    return report


def main():
    report = evaluate()
    print(f"Paraphrases generated by: {report['paraphrase_model']}  |  "
          f"sample size: {report['sample_size']}\n")
    print(f"{'threshold':>9}  {'hit_rate':>9}  {'correct_match_rate':>19}")
    for t in THRESHOLDS:
        r = report['results_by_threshold'][str(t)]
        cm = f"{r['correct_match_rate_of_hits']:.3f}" if r['correct_match_rate_of_hits'] is not None else 'n/a'
        print(f"{t:>9.2f}  {r['hit_rate']:>9.3f}  {cm:>19}")
    print(f"\nSaved full report to {OUTPUT_PATH}")


if __name__ == '__main__':
    main()
